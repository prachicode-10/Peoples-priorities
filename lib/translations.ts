export type TranslationDictionary = typeof en;

// Deep partial helper to allow any language to override keys while keeping full type-safety
export type DeepPartial<T> = {
  [P in keyof T]?: T[P] extends object ? DeepPartial<T[P]> : T[P];
};

// Helper function to recursively merge language dictionary over English defaults
export function mergeWithFallback<T extends Record<string, any>>(
  base: T,
  overrides?: DeepPartial<T>
): T {
  if (!overrides) return base;
  const result: any = { ...base };
  for (const key of Object.keys(overrides)) {
    const overrideVal = (overrides as any)[key];
    const baseVal = (base as any)[key];
    if (
      overrideVal &&
      typeof overrideVal === "object" &&
      !Array.isArray(overrideVal) &&
      baseVal &&
      typeof baseVal === "object"
    ) {
      result[key] = mergeWithFallback(baseVal, overrideVal);
    } else if (overrideVal !== undefined && overrideVal !== "") {
      result[key] = overrideVal;
    }
  }
  return result;
}

